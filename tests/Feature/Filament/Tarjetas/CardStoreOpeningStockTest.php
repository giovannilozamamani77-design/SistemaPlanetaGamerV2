<?php

use App\Domain\Incidencias\Models\EconomicIncident;
use App\Domain\Tarjetas\Actions\RecordCardStoreCountAction;
use App\Domain\Tarjetas\Models\CardProduct;
use App\Domain\Tarjetas\Models\CardStock;
use App\Domain\Tarjetas\Models\CardStore;
use App\Domain\Tarjetas\Models\CardStoreCount;
use App\Domain\Tarjetas\Models\CardStoreReserve;
use App\Domain\Tarjetas\Queries\CardStoreSessionQuery;
use App\Filament\Pages\Tarjetas\CardStoreOpening;
use App\Models\User;
use Database\Seeders\Incidencias\IncidenciasPermissionsSeeder;
use Database\Seeders\Tarjetas\CardSalesPermissionsSeeder;
use Database\Seeders\Tarjetas\CardStoreSessionsPermissionsSeeder;
use Database\Seeders\Tarjetas\TarjetasPermissionsSeeder;
use Database\Seeders\Usuarios\UsuariosPermissionsSeeder;
use Filament\Facades\Filament;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Livewire\Livewire;

uses(RefreshDatabase::class);
it('C189 shows physical stock before cash while zero cuts stay folded and reserved cards remain countable', function () {
    expect(config('database.connections.sqlite.database'))->toBe(':memory:');
    $this->seed([UsuariosPermissionsSeeder::class, TarjetasPermissionsSeeder::class, CardSalesPermissionsSeeder::class, CardStoreSessionsPermissionsSeeder::class, IncidenciasPermissionsSeeder::class]);
    Filament::setCurrentPanel(Filament::getPanel('inicio'));
    $a = User::factory()->create();
    $a->assignRole('cajera');
    $b = User::factory()->create();
    $b->assignRole('cajera');
    $this->actingAs($a);
    $store = CardStore::create(['code' => 'TIENDA', 'cash_balance_cents' => 10000, 'initialized_at' => now(), 'initialized_by' => $a->id]);
    $products = [];
    foreach (['ENTEL' => [1000, 5], 'TIGO' => [1000, 0], 'VIVA' => [4000, 0]] as $company => [$face,$quantity]) {
        $p = CardProduct::create(['company' => $company, 'face_value_cents' => $face, 'purchase_price_cents' => $face, 'normal_price_cents' => $face, 'wholesale_price_cents' => $face, 'is_active' => true, 'revision' => 1, 'created_by' => $a->id]);
        CardStock::create(['card_store_id' => $store->id, 'card_product_id' => $p->id, 'quantity' => $quantity]);
        $products[$company] = $p;
    }
    $query = app(CardStoreSessionQuery::class);
    $action = app(RecordCardStoreCountAction::class);
    $open = $query->form($a, 'OPEN');
    $ti = array_search($products['TIGO']->id, array_column($open['stocks'], 'product_id'));
    $ei = array_search($products['ENTEL']->id, array_column($open['stocks'], 'product_id'));
    $vi = array_search($products['VIVA']->id, array_column($open['stocks'], 'product_id'));
    $open['stocks'][$ti]['quantity'] = 2;
    $open['reason'] = 'Tarjetas reservadas encontradas';
    $action->open($a, $open);
    $action->close($a, $query->form($a, 'CLOSE'));
    expect($products['TIGO']->stock()->first()->quantity)->toBe(0);
    expect(CardStoreReserve::sole()->held_amount)->toBe(2);
    $this->actingAs($b);
    $page = Livewire::test(CardStoreOpening::class);
    $html = $page->instance()->getSchema('form')->toHtml();
    $dom = new DOMDocument;
    $dom->loadHTML($html, LIBXML_NOERROR | LIBXML_NOWARNING);
    $xpath = new DOMXPath($dom);
    $shown = $xpath->query('//input[starts-with(@id,"store-count-") and not(ancestor::details)]');
    $folded = $xpath->query('//details[@aria-label="Cortes sin existencias esperadas"]//input[starts-with(@id,"store-count-")]');
    expect($shown->length)->toBe(2);
    expect($folded->length)->toBe(1);
    expect($folded->item(0)->getAttribute('id'))->toBe('store-count-'.$products['VIVA']->id);
    expect($xpath->query('//details[@aria-label="Cortes sin existencias esperadas" and @open]')->length)->toBe(0);
    expect(strpos($html, 'Conteo de tarjetas por empresa'))->toBeLessThan(strpos($html, 'Efectivo contado'));
    $page->set('data.stocks.'.$ei.'.quantity', '0');
    $zeroHtml = $page->instance()->getSchema('form')->toHtml();
    $dom->loadHTML($zeroHtml, LIBXML_NOERROR | LIBXML_NOWARNING);
    expect((new DOMXPath($dom))->query('//input[@id="store-count-'.$products['ENTEL']->id.'" and not(ancestor::details)]')->length)->toBe(1);
    $page->call('cancelOpening');
    expect(CardStoreCount::count())->toBe(2);
    $page = Livewire::test(CardStoreOpening::class)->assertSet('data.stocks.'.$ei.'.quantity', 5)->set('data.stocks.'.$vi.'.quantity', '1')->call('confirmOpening')->assertHasErrors(['data.reason']);
    $page->set('data.reason', 'Cabina encontrada en recepción')->call('confirmOpening')->assertHasNoErrors();
    $count = CardStoreCount::latest('id')->first();
    expect($count->shortage_cents)->toBe(0);
    expect(collect($count->lines)->keyBy('product_id')[$products['VIVA']->id]['counted'])->toBe(1);
    expect(CardStoreReserve::where('card_product_id', $products['TIGO']->id)->sole()->held_amount)->toBe(2);
    expect(CardStoreReserve::where('card_product_id', $products['VIVA']->id)->sole()->held_amount)->toBe(1);
    expect(EconomicIncident::count())->toBe(0);
    expect(CardStore::sole()->cash_balance_cents)->toBe(10000);
});
